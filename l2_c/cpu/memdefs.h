#pragma once

// 16-bit RAM defs
// IBAR in use

#define S_SYS_RAM_16 0x0000
#define E_SYS_RAM_16 0xEFFF

#define S_AUDIO_RAM_16 0xF000
#define E_AUDIO_RAM_16 0xF0FF

#define S_MOUSE_RAM_16 0xF100
#define E_MOUSE_RAM_16 0xF1FF

#define S_KEYBOARD_RAM_16 0xF200
#define E_KEYBOARD_RAM_16 0xF2FF

#define S_PIT_RAM_16 0xF300
#define E_PIT_RAM_16 0xF3FF

#define S_VIDEO_RAM_16 0xF400
#define E_VIDEO_RAM_16 0xF4FF

// ^ VRAM banked

// 32-bit RAM defs
#define S_SYS_RAM_32 0x00000000
#define E_SYS_RAM_32 0x6FFFFFFF

#define S_VIDEO_RAM_32 0x70000000
#define E_VIDEO_RAM_32 0x7FFFFFFF

// Half-IBAR blocks from here on
#define S_AUDIO_RAM_32 0x80000000
#define E_AUDIO_RAM_32 0x8000FFFF

#define S_MOUSE_RAM_32 0x80010000
#define E_MOUSE_RAM_32 0x8001FFFF

#define S_KEYBOARD_RAM_32 0x80020000
#define E_KEYBOARD_RAM_32 0x8002FFFF

#define S_PIT_RAM_32 0x80030000
#define E_PIT_RAM_32 0x8003FFFF
